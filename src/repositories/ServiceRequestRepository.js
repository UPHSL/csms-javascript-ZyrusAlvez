import { openDatabase } from "../database/connection.js";
import { ServiceRequest } from "../models/ServiceRequest.js";

// shared by listing and every search/filter query so all results use one order.
// date_requested is stored as YYYY-MM-DD text, so text ordering is chronological.
const QUERY_ORDER = "date_requested DESC, id DESC";

// makes %, _ and \ in user input match literally instead of acting as LIKE wildcards
function escapeLikePattern(value) {
  return value.replace(/[\\%_]/g, (character) => `\\${character}`);
}

export class ServiceRequestRepository {
  // opens its own connection; omitting dbPath falls back to the default database
  constructor(dbPath) {
    this.db = openDatabase(dbPath);
    this.initialize();
  }

  close() {
    this.db.close();
  }

  // no need to call this method outside the class; its in the constructor
  // stores only resident_id; Resident information stays in the residents table
  initialize() {
    this.db.exec(`
      CREATE TABLE IF NOT EXISTS service_requests (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        resident_id INTEGER NOT NULL,
        service_type TEXT NOT NULL,
        description TEXT NOT NULL,
        date_requested TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'Pending'
      )
    `);
  }

  // converts a database row into a ServiceRequest instance
  toServiceRequest(row) {
    return new ServiceRequest({
      id: row.id,
      residentId: row.resident_id,
      serviceType: row.service_type,
      description: row.description,
      dateRequested: row.date_requested,
      status: row.status
    });
  }

  findById(id) {
    const row = this.db.prepare("SELECT * FROM service_requests WHERE id = ?").get(id);
    return row ? this.toServiceRequest(row) : null;
  }

  // every persisted Service Request in the required deterministic order;
  // an empty table yields an empty array
  findAll() {
    const rows = this.db.prepare(
      `SELECT * FROM service_requests
       ORDER BY ${QUERY_ORDER}`
    ).all();

    return rows.map((row) => this.toServiceRequest(row));
  }

  // the most recent Service Requests using the same T11 order, limited in SQL
  findRecent(limit) {
    const rows = this.db.prepare(
      `SELECT * FROM service_requests
       ORDER BY ${QUERY_ORDER}
       LIMIT ?`
    ).all(limit);

    return rows.map((row) => this.toServiceRequest(row));
  }

  // aggregate: total number of persisted Service Requests (every status), counted by SQLite
  countAll() {
    const row = this.db.prepare("SELECT COUNT(*) AS count FROM service_requests").get();
    return Number(row.count);
  }

  // aggregate: { status: count } for every status present, counted by SQLite in one query
  countByStatus() {
    const rows = this.db.prepare(
      "SELECT status, COUNT(*) AS count FROM service_requests GROUP BY status"
    ).all();

    return Object.fromEntries(rows.map((row) => [row.status, Number(row.count)]));
  }

  // filtering happens in SQL, not in application memory.
  // searchTerm: partial, case-insensitive match on service_type OR description.
  // status: exact match on status.
  // Both are optional; when both are given they are combined with AND.
  // A single WHERE over one table, so a row matching both text fields is returned once.
  search({ searchTerm = null, status = null } = {}) {
    const conditions = [];
    const parameters = [];

    if (searchTerm !== null) {
      const pattern = `%${escapeLikePattern(searchTerm.toLowerCase())}%`;

      conditions.push(
        `(LOWER(service_type) LIKE ? ESCAPE '\\'
          OR LOWER(description) LIKE ? ESCAPE '\\')`
      );
      parameters.push(pattern, pattern);
    }

    if (status !== null) {
      conditions.push("status = ?");
      parameters.push(status);
    }

    const whereClause =
      conditions.length > 0
        ? `WHERE ${conditions.join(" AND ")}`
        : "";

    const rows = this.db.prepare(
      `SELECT * FROM service_requests
       ${whereClause}
       ORDER BY ${QUERY_ORDER}`
    ).all(...parameters);

    return rows.map((row) => this.toServiceRequest(row));
  }

  // the id is generated by the database (AUTOINCREMENT), never supplied by the caller
  save(serviceRequest) {
    const result = this.db.prepare(
      `INSERT INTO service_requests (resident_id, service_type, description, date_requested, status)
       VALUES (?, ?, ?, ?, ?)`
    ).run(
      serviceRequest.residentId,
      serviceRequest.serviceType,
      serviceRequest.description,
      serviceRequest.dateRequested,
      serviceRequest.status
    );

    return this.findById(result.lastInsertRowid);
  }

  // persistence only: writes the status of the Service Request identified by id.
  // The transition rules are decided by ServiceRequestStatusService before this is called.
  updateStatus(id, status) {
    const result = this.db.prepare(
      "UPDATE service_requests SET status = ? WHERE id = ?"
    ).run(status, id);

    return result.changes > 0 ? this.findById(id) : null;
  }
}
